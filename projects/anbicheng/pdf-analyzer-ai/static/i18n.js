// 当前语言（持久化到 localStorage，默认日文）
var currentLang = localStorage.getItem("pdf_lang") || "ja";

/** 取翻译文本，找不到时原样返回 key */
function t(key) {
  return (i18n[currentLang] && i18n[currentLang][key]) || key;
}

/** 将所有 data-i18n 元素更新为当前语言文本 */
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(function(el) {
    var key = el.getAttribute("data-i18n");
    var text = t(key);
    if (text) el.textContent = text;
  });
  // placeholder 属性翻译
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function(el) {
    var key = el.getAttribute("data-i18n-placeholder");
    var text = t(key);
    if (text) el.setAttribute("placeholder", text);
  });
  // title 属性翻译
  document.querySelectorAll("[data-i18n-title]").forEach(function(el) {
    var key = el.getAttribute("data-i18n-title");
    var text = t(key);
    if (text) el.setAttribute("title", text);
  });
  document.documentElement.lang = currentLang === "ja" ? "ja" : "zh-CN";
  document.title = currentLang === "ja"
    ? "PDF Analyzer - インテリジェント文書解析"
    : "PDF Analyzer - 智能文档解析";
  var langLabel = document.getElementById("lang-label");
  if (langLabel) langLabel.textContent = t("lang_toggle_label");
}

/** 切换语言并刷新界面 */
function switchLang() {
  currentLang = currentLang === "ja" ? "zh" : "ja";
  localStorage.setItem("pdf_lang", currentLang);
  applyI18n();
}
